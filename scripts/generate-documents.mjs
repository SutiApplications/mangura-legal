import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const privacyPolicy = readFileSync(join(root, "PRIVACY_POLICY.md"), "utf8");
const termsOfUse = readFileSync(join(root, "TERMS_OF_USE.md"), "utf8");
const sourceConfigurationGuide = readFileSync(join(root, "SOURCE_CONFIGURATION.md"), "utf8");
const output = `// Generated by scripts/generate-documents.mjs. Do not edit directly.\n\nexport const privacyPolicy = ${JSON.stringify(privacyPolicy)};\n\nexport const termsOfUse = ${JSON.stringify(termsOfUse)};\n\nexport const sourceConfigurationGuide = ${JSON.stringify(sourceConfigurationGuide)};\n`;

writeFileSync(join(root, "lib/generated-legal-documents.ts"), output);
