import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const privacyPolicy = readFileSync(join(root, "PRIVACY_POLICY.md"), "utf8");
const appStorePrivacyAnswers = readFileSync(join(root, "APP_STORE_PRIVACY_ANSWERS.md"), "utf8");
const output = `// Generated by scripts/generate-documents.mjs. Do not edit directly.\n\nexport const privacyPolicy = ${JSON.stringify(privacyPolicy)};\n\nexport const appStorePrivacyAnswers = ${JSON.stringify(appStorePrivacyAnswers)};\n`;

writeFileSync(join(root, "lib/generated-legal-documents.ts"), output);
